/** The checker step every maker-checker voucher needs (require_journal_approval is on in all four companies). */
const approveAsCfo = (id: string, what: string, impact: string) => ({
  id,
  title: `Approve the ${what} as CFO`,
  body: `Switch to CFO. In Approvals, select the ${what} you just submitted (in Aster Trading, not PAY-2026-0003, a seeded expense that is also waiting), check its lines and click Approve & post. A maker can never approve their own voucher.`,
  route: "/approvals",
  target: "approvals-approve",
  role: "cfo" as const,
  expect: did("journal.posted", { role: "cfo" }),
  impact,
});


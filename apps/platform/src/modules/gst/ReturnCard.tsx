import React from "react";
import { Download } from "lucide-react";
import { Button } from "@/components/ui/Button";
import { Badge } from "@/components/ui/Badge";
import { formatINR } from "@/lib/formatters/currency";
import type { ReturnResult } from "@/lib/gst/returns";

/** Summary, blocking errors and (optionally) the JSON download for one built return. */
export function ReturnCard({
  title,
  result,
  notCovered,
  onDownload,
}: {
  title: string;
  result: ReturnResult;
  notCovered: string[];
  onDownload?: () => void;
}) {
  const cols = ["txval", "camt", "samt", "iamt", "csamt"] as const;
  return (
    <div className="rounded-panel border border-line bg-surface p-5 space-y-4">
      <div className="flex items-center justify-between border-b border-line pb-3">
        <h2 className="text-[15px] font-semibold tracking-tight text-ink">{title}</h2>
        {result.errors.length ? (
          <Badge variant="danger">{result.errors.length} blocking</Badge>
        ) : (
          <Badge variant="success">Validated</Badge>
        )}
      </div>

      <div className="overflow-x-auto">
        <table className="w-full text-[13.5px]">
          <thead>
            <tr className="text-[12.5px] text-ink-muted text-left">
              <th scope="col" className="font-medium py-2">Section</th>
              {["Taxable", "CGST", "SGST", "IGST", "Cess"].map((h) => (
                <th scope="col" key={h} className="font-medium py-2 text-right">{h}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {result.summary.map((row) => (
              <tr key={row.section} className="border-t border-line">
                <td className="py-2 text-[13px] text-ink-soft">{row.section}</td>
                {row.amounts ? (
                  cols.map((c) => (
                    <td key={c} className="py-2 text-right tabular-nums text-ink">
                      {formatINR(row.amounts![c], { showCurrencySymbol: false })}
                    </td>
                  ))
                ) : (
                  <td colSpan={5} className="py-2 text-right text-ink-muted">Not computed</td>
                )}
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {result.errors.length > 0 && (
        <ul className="rounded-ctl bg-bad-wash border border-bad/25 p-4 text-[13px] text-bad space-y-1 list-disc list-inside">
          {result.errors.map((e, i) => (
            <li key={i}>{e}</li>
          ))}
        </ul>
      )}

      <details className="text-[13px] text-ink-muted">
        <summary className="cursor-pointer">Not generated by Deku yet (fill these on the portal)</summary>
        <ul className="list-disc list-inside mt-1 space-y-0.5">
          {notCovered.map((n) => (
            <li key={n}>{n}</li>
          ))}
        </ul>
      </details>

      {onDownload && (
        <Button variant="primary" size="sm" onClick={onDownload} disabled={!result.json}>
          <Download className="h-4 w-4" />
          Download {title} JSON
        </Button>
      )}
    </div>
  );
}
